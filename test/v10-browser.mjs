import assert from 'node:assert/strict';
import puppeteer from 'puppeteer-core';
import {createServer} from 'vite';
const server=await createServer({root:process.cwd(),server:{host:'127.0.0.1',port:4194,strictPort:true}});await server.listen();
const browser=await puppeteer.launch({headless:true,executablePath:process.env.CHROME_PATH||'/usr/bin/google-chrome',args:['--no-sandbox','--disable-setuid-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage(),output=await browser.newPage();
const errs=[];page.on('pageerror',e=>errs.push('studio: '+e.message));output.on('pageerror',e=>errs.push('output: '+e.message));
try{
 await page.setViewport({width:1536,height:1050});await output.setViewport({width:1280,height:720});
 await page.goto('http://127.0.0.1:4194/v10.html',{waitUntil:'networkidle0'});
 await page.waitForSelector('#scene-list .scene-card');
 assert.equal(await page.$$('#scene-list .scene-card').then(x=>x.length),1);
 await output.goto('http://127.0.0.1:4194/v10-output.html',{waitUntil:'networkidle0'});
 await output.waitForFunction(()=>document.querySelector('#output-connection').hidden,{timeout:6000});
 console.log('PASS synchronized studio/output windows');
 await page.click('#add-scene');
 await page.waitForFunction(()=>document.querySelectorAll('#scene-list .scene-card').length===2);
 await page.$eval('#scene-title',e=>{e.value='Knight Movement';e.dispatchEvent(new Event('input',{bubbles:true}));});
 await page.select('#template','board-presenter');
 await output.waitForFunction(()=>document.querySelector('#video-title').textContent==='Knight Movement'&&document.querySelector('#recording-stage').dataset.template==='board-presenter',{timeout:4000});
 console.log('PASS scene creation, editing and template sync');
 await page.$eval('#scene-notes',e=>{e.value='PRIVATE TEACHER ONLY SCRIPT';e.dispatchEvent(new Event('input',{bubbles:true}));});
 assert.equal(await output.evaluate(()=>document.body.textContent.includes('PRIVATE TEACHER ONLY SCRIPT')),false);
 console.log('PASS private teleprompter does not leak into recording');
 await page.click('#add-reveal');
 await page.select('#reveal-type','text');
 await page.$eval('#reveal-value',e=>{e.value='The knight moves in an L shape';e.dispatchEvent(new Event('input',{bubbles:true}));});
 await page.click('#update-reveal');
 await output.waitForFunction(()=>document.querySelector('#video-explanation')?.textContent.includes('L shape'),{timeout:4000});
 console.log('PASS progressive reveal text');
 await page.click('#restart-scene');
 await output.waitForFunction(()=>document.querySelector('#video-explanation')?.textContent.trim()==='',{timeout:4000});
 await page.click('#next-reveal');
 await output.waitForFunction(()=>document.querySelector('#video-explanation')?.textContent.includes('L shape'),{timeout:4000});
 console.log('PASS replayable reveal sequence');
 await page.click('#export-lesson');
 const count=await page.evaluate(()=>JSON.parse(localStorage.getItem('chess-classroom-v10-lesson')).scenes.length);
 assert.equal(count,2);
 assert.equal(await output.$('.studio-top'),null);
 assert.ok(await output.$eval('.presenter-area',e=>e.getBoundingClientRect().width>100));
 console.log('PASS persistent lesson and camera-safe presentation area');
 assert.deepEqual(errs,[]);console.log('PASS V10 browser workflow');
}catch(error){console.error('V10 BROWSER FAILURE:',error.stack||error,errs);try{await page.screenshot({path:'v10-studio-failure.png'});await output.screenshot({path:'v10-output-failure.png'});}catch{}process.exitCode=1;}finally{await page.close();await output.close();await browser.close();await server.close();}
